export function getCharacterTemplate(id: string): CharacterTemplate {
  return (
    CHARACTER_TEMPLATES.find((c) => c.id === id) ?? CHARACTER_TEMPLATES[0]
  );
}

export function getCharactersForSubject(subject: SubjectId): CharacterTemplate[] {
  return CHARACTER_TEMPLATES.filter(
    (c) => c.subject === subject || c.crossWorldSubject === subject
  );
}
